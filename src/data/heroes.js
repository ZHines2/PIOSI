/**
 * Get hero by name
 * @param {string} name - Hero name
 * @returns {Object|null} - Hero data or null if not found
 */
export function getHeroByName(name) {
  return heroData.find(hero => hero.name === name) || null;
}

/**
 * Get random hero
 * @returns {Object} - Random hero data
 */
export function getRandomHero() {
  return heroData[Math.floor(Math.random() * heroData.length)];
}

/**
 * Filter heroes by criteria
 * @param {Object} criteria - Filter criteria
 * @returns {Array<Object>} - Filtered hero array
 */
export function filterHeroes(criteria = {}) {
  return heroData.filter(hero => {
    return Object.entries(criteria).every(([key, value]) => {
      if (typeof value === 'function') {
        return value(hero[key]);
      }
      return hero[key] === value;
    });
  });
}

/**
 * Get heroes sorted by stat
 * @param {string} stat - Stat to sort by
 * @param {boolean} descending - Sort in descending order
 * @returns {Array<Object>} - Sorted hero array
 */
export function getHeroesSortedBy(stat, descending = true) {
  const sorted = [...heroData].sort((a, b) => {
    const aValue = a[stat] || 0;
    const bValue = b[stat] || 0;
    return descending ? bValue - aValue : aValue - bValue;
  });
  return sorted;
}